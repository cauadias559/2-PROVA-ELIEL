#include <stdio.h>

int main() {
    int a, b;
    
   
    
    printf("\nCALCULADORA SIMPLES\n");
    
    printf("DIGITE O PRIMEIRO NUMERO: ");
    scanf("%d", &a);
    
    printf("\nDIGITE O SEGUNDO NUMERO: ");
    scanf("%d", &b);
    
    
    printf("\nSUBTRACAO: %d ", a - b);
    
    printf("\nADICAO: %d ", a + b);
    
    printf("\nDIVISAO: %d ", a / b);
    
    printf("\nMULTIPLICACAO: %d ", a * b);
    
    
    
    return 0;
    
}
